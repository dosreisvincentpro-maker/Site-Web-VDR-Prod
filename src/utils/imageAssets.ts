/**
 * Handle image load error by cycling through backup sources
 */
export function handleImageError(
  event: React.SyntheticEvent<HTMLImageElement, Event>,
  bundledBackup: string,
  externalFallback: string
) {
  const img = event.currentTarget;
  if (!img.dataset.fallbackLevel) {
    img.dataset.fallbackLevel = '1';
    img.src = bundledBackup;
  } else if (img.dataset.fallbackLevel === '1') {
    img.dataset.fallbackLevel = '2';
    img.src = externalFallback;
  }
}
